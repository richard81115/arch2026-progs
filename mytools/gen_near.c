/* Host tool: list every state within 5 moves of the solved cube, with its
 * distance and the first move of a shortest path back, sorted by key.
 *
 *   gen_near      C header for src/rubik/
 *   gen_near asm  assembly data for src/rubik/
 *
 * key   = p << 10 | o (p: permutation rank, o: orientation rank)
 * entry = key << 7 | distance << 4 | move, move = face * 3 + turn
 */
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "../src/rubik/rubik_tables.h"

enum { MAX_DIST = 5, KEYS = 5040 << 10, UNSEEN = 0xFF };

static uint8_t dist[KEYS];
static uint8_t back[KEYS];
static uint32_t queue[16384];

int main(int argc, char **argv)
{
    int as_asm = argc > 1 && strcmp(argv[1], "asm") == 0;
    unsigned per_dist[MAX_DIST + 1] = {0};
    unsigned count = 0;
    size_t head = 0, tail = 0;

    memset(dist, UNSEEN, sizeof dist);
    dist[0] = 0;
    queue[tail++] = 0;
    while (head < tail) {
        uint32_t key = queue[head++];
        if (dist[key] == MAX_DIST)
            continue;
        for (unsigned face = 0; face < 3; face++) {
            uint16_t p = (uint16_t) (key >> 10), o = (uint16_t) (key & 1023);
            for (unsigned turn = 0; turn < 3; turn++) {
                p = perm_move[face][p];
                o = orient_move[face][o];
                uint32_t next = ((uint32_t) p << 10) | o;
                if (dist[next] != UNSEEN)
                    continue;
                dist[next] = (uint8_t) (dist[key] + 1);
                back[next] = (uint8_t) (face * 3 + (2 - turn));
                queue[tail++] = next;
            }
        }
    }

    for (uint32_t k = 0; k < KEYS; k++)
        if (dist[k] != UNSEEN) {
            per_dist[dist[k]]++;
            count++;
        }
    for (unsigned d = 0; d <= MAX_DIST; d++)
        fprintf(stderr, "distance %u: %u\n", d, per_dist[d]);
    fprintf(stderr, "total: %u entries, %u bytes\n", count, count * 4);

    if (as_asm)
        printf(
            "# Generated by mytools/gen_near.c; do not edit.\n"
            "# entry = key << 7 | distance << 4 | move, key = p << 10 | o\n"
            "    .section .rodata\n"
            "    .align  2\n"
            "    .globl  rubik_near_table\n"
            "rubik_near_table:\n");
    else
        printf(
            "/* Generated by mytools/gen_near.c; do not edit.\n"
            " * entry = key << 7 | distance << 4 | move, key = p << 10 | o\n"
            " */\n"
            "#define NEAR_COUNT %uu\n"
            "static const uint32_t near_table[NEAR_COUNT] = {\n",
            count);

    unsigned col = 0;
    for (uint32_t k = 0; k < KEYS; k++) {
        if (dist[k] == UNSEEN)
            continue;
        uint32_t entry = (k << 7) | ((uint32_t) dist[k] << 4) | back[k];
        if (as_asm)
            printf("%s0x%08x", col == 0 ? "    .word   " : ", ", entry);
        else
            printf("%s0x%08x,", col == 0 ? "    " : " ", entry);
        if (++col == 6) {
            printf("\n");
            col = 0;
        }
    }
    if (col != 0)
        printf("\n");
    if (!as_asm)
        printf("};\n");
    else
        printf("    .word   0xffffffff              # sentinel\n");
    return 0;
}
